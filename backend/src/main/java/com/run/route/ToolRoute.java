package com.run.route;

import com.run.auth.AggregatePermission;
import com.run.auth.Authenticator;
import com.run.auth.TokenBasicAuthHandler;
import com.run.auth.constants.PermissionConstants;
import com.run.common.route.IRoute;
import com.run.handler.tool.IToolFolderHandler;
import com.run.handler.tool.IToolHandler;
import com.run.handler.tool.impl.ToolFolderHandlerImpl;
import com.run.handler.tool.impl.ToolHandlerImpl;
import io.swagger.v3.oas.models.OpenAPI;
import io.vertx.ext.web.Router;
import io.vertx.ext.web.handler.BodyHandler;

import javax.inject.Inject;
import javax.inject.Named;

public class ToolRoute implements IRoute {
    protected Router apiRoute;
    protected TokenBasicAuthHandler tokenBasicAuthHandler;
    private final IToolHandler iToolHandler;
    private final IToolFolderHandler iToolFolderHandler;
    protected OpenAPI openAPI;

    @Inject
    public ToolRoute(@Named("apiRoute") Router apiRoute, OpenAPI openAPI,
                     @Named("tokenBasicAuthHandler") TokenBasicAuthHandler tokenBasicAuthHandler,
                     ToolHandlerImpl toolHandler,
                     ToolFolderHandlerImpl toolFolderHandler) {
        this.apiRoute = apiRoute;
        this.openAPI = openAPI;
        this.iToolHandler = toolHandler;
        this.tokenBasicAuthHandler = tokenBasicAuthHandler;
        this.iToolFolderHandler = toolFolderHandler;
    }

    @Override
    public void initRoute() {
        // ===================== 资源 =====================
        apiRoute.get("/tool/resources/:resourceId")
                .handler(tokenBasicAuthHandler)
                .handler(Authenticator.builder()
                        .addPermission(AggregatePermission.builder()
                                .addPermission(PermissionConstants.TOOL_READ)
                                .addPermission(PermissionConstants.TOOL_READ.getResourcePermission())
                                .compare(PermissionConstants.Compare.AND).build())
                        .addRole(PermissionConstants.Role.ADMIN)
                        .compare(PermissionConstants.Compare.OR)
                        .build())
                .handler(iToolHandler::get);

        apiRoute.put("/tool/resources/:resourceId")
                .handler(BodyHandler.create())
                .handler(tokenBasicAuthHandler)
                .handler(Authenticator.builder()
                        .addPermission(AggregatePermission.builder()
                                .addPermission(PermissionConstants.TOOL_EDIT)
                                .addPermission(PermissionConstants.TOOL_EDIT.getResourcePermission())
                                .compare(PermissionConstants.Compare.AND).build())
                        .addRole(PermissionConstants.Role.ADMIN)
                        .compare(PermissionConstants.Compare.OR)
                        .build())
                .handler(iToolHandler::edit);

        apiRoute.delete("/tool/resources/:resourceId")
                .handler(tokenBasicAuthHandler)
                .handler(Authenticator.builder()
                        .addPermission(AggregatePermission.builder()
                                .addPermission(PermissionConstants.TOOL_DELETE)
                                .addPermission(PermissionConstants.TOOL_DELETE.getResourcePermission())
                                .compare(PermissionConstants.Compare.AND).build())
                        .addRole(PermissionConstants.Role.ADMIN)
                        .compare(PermissionConstants.Compare.OR)
                        .build())
                .handler(iToolHandler::delete);

        apiRoute.post("/tool/resources/:resourceId/modify-name")
                .handler(BodyHandler.create())
                .handler(tokenBasicAuthHandler)
                .handler(Authenticator.builder()
                        .addPermission(AggregatePermission.builder()
                                .addPermission(PermissionConstants.TOOL_EDIT)
                                .addPermission(PermissionConstants.TOOL_EDIT.getResourcePermission())
                                .compare(PermissionConstants.Compare.AND).build())
                        .addRole(PermissionConstants.Role.ADMIN)
                        .compare(PermissionConstants.Compare.OR)
                        .build())
                .handler(iToolHandler::rename);

        // ===================== 文件夹 =====================
        apiRoute.post("/tool/folders/:folderId/modify-name")
                .handler(BodyHandler.create())
                .handler(tokenBasicAuthHandler)
                .handler(Authenticator.builder()
                        .addPermission(AggregatePermission.builder()
                                .addPermission(PermissionConstants.TOOL_FOLDER_EDIT)
                                .addPermission(PermissionConstants.TOOL_FOLDER_EDIT.getFolderPermission())
                                .compare(PermissionConstants.Compare.AND).build())
                        .addRole(PermissionConstants.Role.ADMIN)
                        .compare(PermissionConstants.Compare.OR)
                        .build())
                .handler(iToolFolderHandler::rename);

        apiRoute.get("/tool/folders/:folderId")
                .handler(tokenBasicAuthHandler)
                .handler(Authenticator.builder()
                        .addPermission(AggregatePermission.builder()
                                .addPermission(PermissionConstants.TOOL_READ)
                                .addPermission(PermissionConstants.TOOL_READ.getFolderPermission())
                                .compare(PermissionConstants.Compare.AND).build())
                        .addRole(PermissionConstants.Role.ADMIN)
                        .compare(PermissionConstants.Compare.OR)
                        .build())
                .handler(iToolFolderHandler::get);

        apiRoute.delete("/tool/folders/:folderId")
                .handler(tokenBasicAuthHandler)
                .handler(Authenticator.builder()
                        .addPermission(AggregatePermission.builder()
                                .addPermission(PermissionConstants.TOOL_FOLDER_DELETE)
                                .addPermission(PermissionConstants.TOOL_FOLDER_DELETE.getFolderPermission())
                                .compare(PermissionConstants.Compare.AND).build())
                        .addRole(PermissionConstants.Role.ADMIN)
                        .compare(PermissionConstants.Compare.OR)
                        .build())
                .handler(iToolFolderHandler::delete);

        apiRoute.post("/tool/folders/:folderId")
                .handler(BodyHandler.create())
                .handler(tokenBasicAuthHandler)
                .handler(Authenticator.builder()
                        .addPermission(AggregatePermission.builder()
                                .addPermission(PermissionConstants.TOOL_FOLDER_CREATE)
                                .addPermission(PermissionConstants.TOOL_FOLDER_CREATE.getFolderPermission())
                                .compare(PermissionConstants.Compare.AND).build())
                        .addRole(PermissionConstants.Role.ADMIN)
                        .compare(PermissionConstants.Compare.OR)
                        .build())
                .handler(iToolFolderHandler::create);

        apiRoute.get("/tool/folders/:folderId/subtree")
                .handler(tokenBasicAuthHandler)
                .handler(Authenticator.builder()
                        .addPermission(AggregatePermission.builder()
                                .addPermission(PermissionConstants.TOOL_READ)
                                .compare(PermissionConstants.Compare.AND).build())
                        .addRole(PermissionConstants.Role.ADMIN)
                        .addRole(PermissionConstants.Role.USER)
                        .compare(PermissionConstants.Compare.OR)
                        .build())
                .handler(iToolHandler::tree);

        apiRoute.get("/tool/folders/:folderId/resources")
                .handler(tokenBasicAuthHandler)
                .handler(Authenticator.builder()
                        .addPermission(AggregatePermission.builder()
                                .addPermission(PermissionConstants.TOOL_READ)
                                .compare(PermissionConstants.Compare.AND).build())
                        .addRole(PermissionConstants.Role.ADMIN)
                        .addRole(PermissionConstants.Role.USER)
                        .compare(PermissionConstants.Compare.OR)
                        .build())
                .handler(iToolHandler::list);

        apiRoute.post("/tool/folders/:folderId/resources")
                .handler(BodyHandler.create())
                .handler(tokenBasicAuthHandler)
                .handler(Authenticator.builder()
                        .addPermission(AggregatePermission.builder()
                                .addPermission(PermissionConstants.TOOL_CREATE)
                                .addPermission(PermissionConstants.TOOL_CREATE.getFolderPermission())
                                .compare(PermissionConstants.Compare.AND).build())
                        .addRole(PermissionConstants.Role.ADMIN)
                        .compare(PermissionConstants.Compare.OR)
                        .build())
                .handler(iToolHandler::create);

        // ===================== 权限 =====================
        apiRoute.get("/tool/permissions/:userId")
                .handler(tokenBasicAuthHandler)
                .handler(Authenticator.builder()
                        .addRole(PermissionConstants.Role.ADMIN)
                        .build())
                .handler(iToolHandler::listResourcePermission);

        apiRoute.put("/tool/permissions/:userId/authorization/:resourceId/:permission")
                .handler(tokenBasicAuthHandler)
                .handler(Authenticator.builder()
                        .addRole(PermissionConstants.Role.ADMIN)
                        .build())
                .handler(iToolHandler::authResourcePermission);
    }

    @Override
    public void initOpenApi() {
    }
}
